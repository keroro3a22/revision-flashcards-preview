const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');

test('home page keeps badges and does not put Game in the topbar', () => {
  const home = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const sheet = home.slice(home.indexOf('id="packs"'), home.indexOf('id="how"'));
  assert.match(home, /id="place-entries"/);
  assert.match(home, /Unlock your badges/);
  assert.match(home, /id="pack-index"/);
  assert.doesNotMatch(home, /detective-peek/);
  assert.doesNotMatch(home, /Be a Detective/);
  assert.doesNotMatch(home, /games-link/);
  assert.doesNotMatch(sheet, /href="game\//);
  assert.doesNotMatch(sheet, /game\/clue-hunt/);
  const nav = home.match(/<nav class="nav-plain"[\s\S]*?<\/nav>/)[0];
  assert.doesNotMatch(nav, />Game</);
  assert.doesNotMatch(home, /class="detective-card"/);
  assert.doesNotMatch(home, /Start Clue Hunt/);
  const css = fs.readFileSync(path.join(root, 'assets/site.css'), 'utf8');
  assert.doesNotMatch(css, /games-link|detective-peek/);
  assert.match(css, /\.sheet \{[^}]*padding:\s*clamp\(4\.4rem, 7vw, 5\.2rem\)/);
});

test('game hub offers two worlds and leaves School Mystery in place', () => {
  const hub = fs.readFileSync(path.join(root, 'game/index.html'), 'utf8');
  assert.match(hub, /href="\.\.\/"/);
  assert.match(hub, />Choose a world</);
  assert.match(hub, /Mystic Mist Isles/);
  assert.match(hub, /After-School Club/);
  assert.match(hub, /href="mystic-mist-isles\/"/);
  assert.match(hub, /href="clue-hunt\/"/);
  assert.match(hub, /illust\/mystic-mist-isles\.png/);
  assert.match(hub, /illust\/after-school-club\.png/);
  assert.match(hub, /huninn\.css/);
  assert.match(hub, /family=Nunito/);
  assert.doesNotMatch(hub, /Fredoka/);
  assert.doesNotMatch(hub, /Noto Sans TC/);
  assert.doesNotMatch(hub, /PingFang/);
  assert.doesNotMatch(hub, />Choose a case</);
  assert.doesNotMatch(hub, />Choose a game</);
  assert.doesNotMatch(hub, /case-book/);
  assert.doesNotMatch(hub, /class="game-card/);
  assert.doesNotMatch(hub, /Easy, fun mystery games/);
  assert.doesNotMatch(hub, /Mixed games/);
  assert.doesNotMatch(hub, /practice-entry\.html/);
  const hold = fs.readFileSync(path.join(root, 'game/mystic-mist-isles/index.html'), 'utf8');
  assert.match(hold, /Mystic Mist Isles/);
  assert.match(hold, /Magic Academy/);
  assert.match(hold, /\.\.\/illust\/mystic-mist-isles\.png/);
  assert.match(hold, /href="\.\.\/"/);
  assert.match(hold, /The Magic Academy is getting ready/);
  assert.doesNotMatch(hold, /Fredoka/);
  assert.doesNotMatch(hold, /clue-hunt/);
  const hunt = fs.readFileSync(path.join(root, 'game/clue-hunt/index.html'), 'utf8');
  assert.match(hunt, /id="fair-map"/);
  assert.match(hunt, /id="notebook"/);
  assert.match(hunt, /src="clue-hunt-state\.js"/);
  assert.doesNotMatch(hunt, /Where is the missing boy/);
  assert.doesNotMatch(hunt, /Who is missing/);
  assert.doesNotMatch(hunt, /answer: "Leo"/);
  assert.doesNotMatch(hunt, /Vocab · Unit/);
  assert.doesNotMatch(hunt, /Grammar ·/);
});
